package com.ryn.skyryn.config;

import net.minecraft.client.Minecraft;

/**
 * Серверный ресурспак: снять его прямо сейчас, не перезаходя.
 *
 * Сам отказ от пака живёт в ResourcePackBypassMixin — он ловит пакет с паком при
 * заходе на SkyBlock, отвечает серверу «принял и загрузил» (иначе Hypixel кикает)
 * и отменяет обработку, так что пак не качается и не применяется.
 *
 * Но пакет приходит ОДИН раз, при заходе. Если игрок включил тумблер, уже стоя на
 * острове, отменять нечего: пак давно применён. Тогда снимаем его тем же способом,
 * каким игра делает это при выходе с сервера — popAll(), после чего ресурсы
 * перезагружаются сами. Серверу мы к этому моменту уже ответили «загрузил», и
 * второго ответа он не ждёт, так что кика не будет.
 *
 * Обратно пак не вернуть: сервер присылает его только при заходе. Выключил тумблер —
 * текстуры вернутся со следующим перезаходом, об этом сказано в подсказке настройки.
 */
public final class ServerPack {

	private ServerPack() { }

	/** Снять серверный пак немедленно. Тихо, без экрана загрузки-ошибки. */
	public static void dropNow() {
		Minecraft mc = Minecraft.getInstance();
		if (mc == null) return;
		try {
			mc.getDownloadedPackSource().popAll();
		} catch (Throwable t) {
			// Не наша вина, если Mojang переименует метод: пак снимется с перезахода.
			SkyLog.d("Не смог снять серверный пак: " + t);
		}
	}
}
